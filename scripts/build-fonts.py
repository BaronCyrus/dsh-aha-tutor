"""Build the board's handwriting web fonts.

    python3 -I scripts/build-fonts.py LXGWWenKaiGB-Regular.ttf OFL-wenkai.txt \\
        caveat-latin-400-normal.woff2 LICENSE-caveat

Sources: LXGW WenKai GB 1.530 Regular (github.com/lxgw/LxgwWenkaiGB) and
Caveat 5.3.0 latin 400 (npm @fontsource/caveat), both SIL OFL 1.1. Needs
fonttools and brotli. Writes assets/fonts/*.woff2 with their licenses, and
src/core/board-fonts.js (the manifest the client's @font-face rules and the
host's font route are built from). Edit this script, not its output.

LXGW WenKai GB is cut down to GB 2312 (6,763 common characters plus its
symbols) and the CJK punctuation, split into slices so a browser downloads
only the ones a board needs; rarer characters fall back to the system Kaiti.
Its license lets subsets converted to WOFF2 for web delivery keep the name.
"""

import hashlib
import io
import os
import shutil
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'fonts')
MANIFEST = os.path.join(ROOT, 'src', 'core', 'board-fonts.js')


def gb2312(rows):
    chars = []
    for row in rows:
        for col in range(0xA1, 0xFF):
            try:
                chars.append(bytes([row, col]).decode('gb2312'))
            except UnicodeDecodeError:
                pass
    return [ord(char) for char in chars]


def ranges(codepoints):
    points = sorted(set(codepoints))
    parts = []
    start = previous = None
    for point in points:
        if start is None:
            start = previous = point
        elif point == previous + 1:
            previous = point
        else:
            parts.append((start, previous))
            start = previous = point
    if start is not None:
        parts.append((start, previous))
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in parts)


def chunks(items, count):
    size = -(-len(items) // count)
    return [items[index:index + size] for index in range(0, len(items), size)]


def subset_woff2(path, codepoints):
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.hinting = False
    options.notdef_outline = True
    options.recalc_bounds = True
    font = TTFont(path, lazy=False)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    buffer = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buffer)
    return buffer.getvalue()


def write(name, data):
    digest = hashlib.sha256(data).hexdigest()[:8]
    file = f'{name}-{digest}.woff2'
    with open(os.path.join(OUT, file), 'wb') as handle:
        handle.write(data)
    return file


def main(wenkai, wenkai_license, caveat, caveat_license):
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)

    cmap = TTFont(wenkai, lazy=True).getBestCmap()
    have = lambda points: [point for point in points if point in cmap]
    symbols = have(
        list(range(0x20, 0x7F))            # ASCII, for glyphs Caveat lacks
        + list(range(0xA0, 0x100))         # Latin-1: ° ± × ÷ · ² ³
        + list(range(0x2010, 0x2070))      # dashes, quotes, ellipsis, ‰ ′ ″ ※
        + list(range(0x2100, 0x2200))      # ℃ № Ⅰ… arrows
        + list(range(0x2200, 0x2300))      # math operators
        + list(range(0x2460, 0x24A0))      # ①…⑳
        + list(range(0x2500, 0x2600))      # box drawing, ○ ● △ □
        + list(range(0x3000, 0x3040))      # CJK punctuation
        + list(range(0xFF01, 0xFF5F))      # fullwidth forms
        + gb2312(range(0xA1, 0xAA))        # the rest of GB 2312's symbols
    )
    common = have(gb2312(range(0xB0, 0xD8)))  # level 1: 3,755 characters
    rarer = have(gb2312(range(0xD8, 0xF8)))   # level 2: 3,008 characters

    entries = []
    for index, points in enumerate([sorted(set(symbols))] + chunks(common, 3) + chunks(rarer, 3)):
        data = subset_woff2(wenkai, points)
        entries.append(('Aha Hand', write(f'wenkai-gb-{index}', data), ranges(points), len(data)))

    # Caveat takes plain Latin only; Chinese quotes and dashes stay in WenKai.
    latin = [point for point in TTFont(caveat, lazy=True).getBestCmap() if point < 0x100 or point in (0x131, 0x152, 0x153, 0x20AC, 0x2122)]
    with open(caveat, 'rb') as handle:
        caveat_bytes = handle.read()
    entries.insert(0, ('Aha Hand Latin', write('caveat-latin', caveat_bytes), ranges(latin), len(caveat_bytes)))

    shutil.copyfile(wenkai_license, os.path.join(OUT, 'OFL-LXGWWenKaiGB.txt'))
    shutil.copyfile(caveat_license, os.path.join(OUT, 'OFL-Caveat.txt'))

    lines = [
        '// Generated by scripts/build-fonts.py from LXGW WenKai GB 1.530 Regular and',
        '// Caveat 5.3.0 (both SIL OFL 1.1; licenses in assets/fonts). Do not edit.',
        '// family: the CSS family the board stack names; file: under assets/fonts.',
        '',
        'export const BOARD_FONT_FILES = Object.freeze([',
    ]
    for family, file, unicode_range, size in entries:
        lines.append(f"  Object.freeze({{ family: '{family}', file: '{file}', bytes: {size}, unicodeRange: '{unicode_range}' }}),")
    lines.append('])')
    with open(MANIFEST, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines) + '\n')

    total = sum(entry[3] for entry in entries)
    for family, file, unicode_range, size in entries:
        print(f'{file:40} {size / 1024:8.1f} KiB  {family}')
    print(f'total {total / 1024 / 1024:.2f} MiB in {len(entries)} files')


if __name__ == '__main__':
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
